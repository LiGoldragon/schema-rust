//! Strict bootstrap Interface and Sema generation.
//!
//! This lane begins after the sole naming authority has authenticated an exact
//! bootstrap transaction. The matching reader is revalidated by Nomos, and
//! Rust is projected from the resulting `WholeLogos` through a caller-supplied
//! sealed Rust vocabulary and explicit external type-path resolver.

use std::path::PathBuf;

use core_ethos::bootstrap::{BootstrapBody, EthosKind};
use core_nomos::{
    BootstrapSliceOneLowering, BootstrapSliceOneLoweringError, ExternalStorageProvenance,
};
use rust_logos::{RustLogos, RustTypePathResolver};
use sema_translator::bootstrap::VerifiedBootstrapAssembly;

use crate::build::{BuildError, FreshnessCheck, GeneratedArtifact};

/// Marker placed ahead of every Rust artifact emitted by the strict bootstrap
/// Interface lane.
pub const BOOTSTRAP_INTERFACE_GENERATED_MARKER: &str =
    "// @generated by schema-rust from an authority-verified bootstrap Interface\n\n";

/// Marker placed ahead of every Rust artifact emitted by the strict bootstrap
/// Sema lane.
pub const BOOTSTRAP_SEMA_GENERATED_MARKER: &str =
    "// @generated by schema-rust from an authority-verified bootstrap Sema\n\n";

/// One complete, explicit bootstrap Interface generation request.
///
/// `assembly` owns the verified encoded-name resolver. `rust` owns the sealed
/// structural Rust vocabulary. `rust_types` owns every external Rust path.
/// This boundary creates none of those inputs and performs no spelling-based
/// identity or path inference.
pub struct BootstrapInterfaceGeneration<'a> {
    assembly: &'a VerifiedBootstrapAssembly,
    rust: &'a RustLogos,
    rust_types: &'a dyn RustTypePathResolver,
    source_path: PathBuf,
    rust_path: PathBuf,
}

impl<'a> BootstrapInterfaceGeneration<'a> {
    /// Seat the complete authority, Nomos, and Rust projection inputs.
    pub fn new(
        assembly: &'a VerifiedBootstrapAssembly,
        rust: &'a RustLogos,
        rust_types: &'a dyn RustTypePathResolver,
        source_path: impl Into<PathBuf>,
        rust_path: impl Into<PathBuf>,
    ) -> Self {
        Self {
            assembly,
            rust,
            rust_types,
            source_path: source_path.into(),
            rust_path: rust_path.into(),
        }
    }

    /// Revalidate and lower the exact prepared transaction, then structurally
    /// project deterministic Rust from `WholeLogos`.
    pub fn generate(
        &self,
    ) -> Result<GeneratedBootstrapInterface, BootstrapInterfaceGenerationError> {
        match &self.assembly.transaction().decoded().document.body {
            BootstrapBody::Interface(_) => {}
            BootstrapBody::Nexus(_) => {
                return Err(BootstrapInterfaceGenerationError::WrongFileKind {
                    found: EthosKind::Nexus,
                });
            }
            BootstrapBody::Sema(_) => {
                return Err(BootstrapInterfaceGenerationError::WrongFileKind {
                    found: EthosKind::Sema,
                });
            }
        }

        let logos = BootstrapSliceOneLowering::new()
            .lower(self.assembly.reader(), self.assembly.transaction())?;
        let projected =
            self.rust
                .emit_with_type_paths(&logos, self.assembly.resolver(), self.rust_types)?;
        let mut rust_source =
            String::with_capacity(BOOTSTRAP_INTERFACE_GENERATED_MARKER.len() + projected.len());
        rust_source.push_str(BOOTSTRAP_INTERFACE_GENERATED_MARKER);
        rust_source.push_str(&projected);

        Ok(GeneratedBootstrapInterface {
            artifacts: GeneratedBootstrapArtifacts::new(
                self.source_path.clone(),
                self.assembly.canonical_source().to_owned(),
                self.rust_path.clone(),
                rust_source,
            ),
        })
    }
}

/// Canonical source and Rust projections of one validated Interface
/// transaction.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct GeneratedBootstrapInterface {
    artifacts: GeneratedBootstrapArtifacts,
}

impl GeneratedBootstrapInterface {
    /// Canonical source projection, including its checked path.
    pub const fn source(&self) -> &GeneratedArtifact {
        self.artifacts.source()
    }

    /// Canonical Rust projection, including its checked path.
    pub const fn rust(&self) -> &GeneratedArtifact {
        self.artifacts.rust()
    }

    /// Require both checked artifacts to equal their canonical projections.
    pub fn assert_checked_in(&self) -> Result<(), BuildError> {
        self.artifacts.assert_checked_in()
    }

    /// Check both projections, or update both when the explicit environment
    /// variable is present.
    pub fn write_or_check(
        &self,
        update_environment_variable: impl Into<String>,
    ) -> Result<(), BuildError> {
        self.artifacts.write_or_check(update_environment_variable)
    }
}

/// Exact refusal from the strict bootstrap Interface generation lane.
#[derive(Debug, thiserror::Error)]
pub enum BootstrapInterfaceGenerationError {
    /// Only the provisional Interface file kind belongs to this generator.
    #[error("bootstrap Interface generation received {found:?} source")]
    WrongFileKind { found: EthosKind },
    /// Nomos rejected the still-authority-branded transaction.
    #[error(transparent)]
    Lowering(#[from] BootstrapSliceOneLoweringError),
    /// The canonical structural Rust projection refused an explicit input.
    #[error(transparent)]
    RustProjection(#[from] rust_logos::Error),
}

/// One complete, explicit bootstrap Sema generation request.
///
/// `assembly` owns the verified encoded-name resolver. `rust` owns the sealed
/// structural Rust vocabulary. `rust_types` owns every external Rust path.
/// `external_storage` carries owner-and-revision-bound archive fingerprints for
/// every nonlocal storage leaf. This boundary creates or infers none of them.
pub struct BootstrapSemaGeneration<'a> {
    assembly: &'a VerifiedBootstrapAssembly,
    rust: &'a RustLogos,
    rust_types: &'a dyn RustTypePathResolver,
    external_storage: &'a [ExternalStorageProvenance],
    source_path: PathBuf,
    rust_path: PathBuf,
}

impl<'a> BootstrapSemaGeneration<'a> {
    /// Seat the complete authority, storage, Nomos, and Rust projection inputs.
    pub fn new(
        assembly: &'a VerifiedBootstrapAssembly,
        rust: &'a RustLogos,
        rust_types: &'a dyn RustTypePathResolver,
        external_storage: &'a [ExternalStorageProvenance],
        source_path: impl Into<PathBuf>,
        rust_path: impl Into<PathBuf>,
    ) -> Self {
        Self {
            assembly,
            rust,
            rust_types,
            external_storage,
            source_path: source_path.into(),
            rust_path: rust_path.into(),
        }
    }

    /// Revalidate and storage-lower the exact prepared transaction, then
    /// structurally project deterministic Rust from `WholeLogos`.
    pub fn generate(&self) -> Result<GeneratedBootstrapSema, BootstrapSemaGenerationError> {
        let BootstrapBody::Sema(_) = &self.assembly.transaction().decoded().document.body else {
            return Err(BootstrapSemaGenerationError::WrongFileKind {
                found: self.assembly.transaction().decoded().document.header.kind,
            });
        };

        let logos = BootstrapSliceOneLowering::new().lower_sema(
            self.assembly.reader(),
            self.assembly.transaction(),
            self.external_storage,
        )?;
        let projected =
            self.rust
                .emit_with_type_paths(&logos, self.assembly.resolver(), self.rust_types)?;
        let mut rust_source =
            String::with_capacity(BOOTSTRAP_SEMA_GENERATED_MARKER.len() + projected.len());
        rust_source.push_str(BOOTSTRAP_SEMA_GENERATED_MARKER);
        rust_source.push_str(&projected);

        Ok(GeneratedBootstrapSema {
            artifacts: GeneratedBootstrapArtifacts::new(
                self.source_path.clone(),
                self.assembly.canonical_source().to_owned(),
                self.rust_path.clone(),
                rust_source,
            ),
        })
    }
}

/// Canonical source and Rust projections of one validated Sema transaction.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct GeneratedBootstrapSema {
    artifacts: GeneratedBootstrapArtifacts,
}

impl GeneratedBootstrapSema {
    /// Canonical source projection, including its checked path.
    pub const fn source(&self) -> &GeneratedArtifact {
        self.artifacts.source()
    }

    /// Canonical Rust projection, including its checked path.
    pub const fn rust(&self) -> &GeneratedArtifact {
        self.artifacts.rust()
    }

    /// Require both checked artifacts to equal their canonical projections.
    pub fn assert_checked_in(&self) -> Result<(), BuildError> {
        self.artifacts.assert_checked_in()
    }

    /// Check both projections, or update both when the explicit environment
    /// variable is present.
    pub fn write_or_check(
        &self,
        update_environment_variable: impl Into<String>,
    ) -> Result<(), BuildError> {
        self.artifacts.write_or_check(update_environment_variable)
    }
}

#[derive(Clone, Debug, Eq, PartialEq)]
struct GeneratedBootstrapArtifacts {
    source: GeneratedArtifact,
    rust: GeneratedArtifact,
}

impl GeneratedBootstrapArtifacts {
    fn new(source_path: PathBuf, source: String, rust_path: PathBuf, rust: String) -> Self {
        Self {
            source: GeneratedArtifact::new(source_path, source),
            rust: GeneratedArtifact::new(rust_path, rust),
        }
    }

    const fn source(&self) -> &GeneratedArtifact {
        &self.source
    }

    const fn rust(&self) -> &GeneratedArtifact {
        &self.rust
    }

    fn assert_checked_in(&self) -> Result<(), BuildError> {
        let check = FreshnessCheck::check_only();
        self.source.check_with(&check)?;
        self.rust.check_with(&check)
    }

    fn write_or_check(
        &self,
        update_environment_variable: impl Into<String>,
    ) -> Result<(), BuildError> {
        let check = FreshnessCheck::from_environment(update_environment_variable);
        self.source.check_with(&check)?;
        self.rust.check_with(&check)
    }
}

/// Exact refusal from the strict bootstrap Sema generation lane.
#[derive(Debug, thiserror::Error)]
pub enum BootstrapSemaGenerationError {
    /// Only the Sema file kind belongs to this generator.
    #[error("bootstrap Sema generation received {found:?} source")]
    WrongFileKind { found: EthosKind },
    /// Nomos rejected the still-authority-branded transaction or storage proof.
    #[error(transparent)]
    Lowering(#[from] BootstrapSliceOneLoweringError),
    /// The canonical structural Rust projection refused an explicit input.
    #[error(transparent)]
    RustProjection(#[from] rust_logos::Error),
}
